object CdnPools {

    private fun ipLong(ip: String): Long? {
        val p = ip.split(".")
        if (p.size != 4) return null
        var v = 0L
        for (s in p) {
            val n = s.toIntOrNull() ?: return null
            if (n !in 0..255) return null
            v = (v shl 8) or n.toLong()
        }
        return v
    }

    private fun inCidr(ip: String, cidr: String): Boolean {
        val slash = cidr.indexOf('/')
        if (slash < 0) return false
        val base = ipLong(cidr.substring(0, slash)) ?: return false
        val prefix = cidr.substring(slash + 1).toIntOrNull() ?: return false
        val v = ipLong(ip) ?: return false
        if (prefix <= 0) return true
        if (prefix >= 32) return v == base
        val mask = (-1L shl (32 - prefix)) and 0xFFFFFFFFL
        return (v and mask) == (base and mask)
    }

